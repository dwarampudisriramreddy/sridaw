import 'dart:ui' as ui show Color;
import 'package:flutter/rendering.dart'
    show Canvas, Paint, PaintingStyle, Rect;

/// A bitmap font. Each glyph is a list of rows; each row is an int whose low
/// [width] bits are the pixels, bit (width-1) being the left-most column.
///
/// Only `draw` touches the canvas, so the font data is trivially unit-testable
/// and usable from golden tests.
class PixelFont {
  final int width;
  final int height;
  final Map<String, List<int>> glyphs;

  const PixelFont(this.width, this.height, this.glyphs);

  bool has(String c) => glyphs.containsKey(c);

  /// Build a new font with [extra] glyphs merged in (used for tests / overrides).
  PixelFont extend(Map<String, List<int>> extra) =>
      PixelFont(width, height, {...glyphs, ...extra});

  void draw(
    Canvas canvas,
    String text,
    int x,
    int y,
    ui.Color color, {
    int scale = 1,
  }) {
    var cx = x;
    final chars = text.split('');
    for (final raw in chars) {
      final upper = raw.toUpperCase();
      if (raw == ' ') {
        cx += (width + 1) * scale;
        continue;
      }
      final glyph = glyphs[raw] ?? glyphs[upper];
      if (glyph == null) {
        // Unknown glyph -> hollow box so text is never silently missing.
        _box(canvas, cx, y, color, scale);
        cx += (width + 1) * scale;
        continue;
      }
      final paint = Paint()
        ..color = color
        ..isAntiAlias = false
        ..style = PaintingStyle.fill;
      for (var row = 0; row < glyph.length; row++) {
        final bits = glyph[row];
        for (var col = 0; col < width; col++) {
          if ((bits >> (width - 1 - col)) & 1 == 1) {
            canvas.drawRect(
              Rect.fromLTWH(
                (cx + col * scale).toDouble(),
                (y + row * scale).toDouble(),
                scale.toDouble(),
                scale.toDouble(),
              ),
              paint,
            );
          }
        }
      }
      cx += (width + 1) * scale;
    }
  }

  void _box(Canvas canvas, int x, int y, ui.Color color, int scale) {
    final paint = Paint()
      ..color = color
      ..isAntiAlias = false
      ..style = PaintingStyle.stroke
      ..strokeWidth = scale.toDouble();
    canvas.drawRect(
      Rect.fromLTWH(
        x.toDouble(),
        y.toDouble(),
        (width * scale).toDouble(),
        (height * scale).toDouble(),
      ),
      paint,
    );
  }

  /// Pixel width of [text], including the 1px inter-glyph gap.
  int measure(String text, {int scale = 1}) {
    if (text.isEmpty) return 0;
    return (text.length * (width + 1) - 1) * scale;
  }
}

